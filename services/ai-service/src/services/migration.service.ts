// ============================================================================
// RUN DATA MIGRATION (Idempotent Atlas Upsert Engine)
// ============================================================================
export async function runDataMigration(): Promise<{
  usersInserted: number;
  tripsInserted: number;
  bookingsInserted: number;
  budgetsInserted: number;
  packingInserted: number;
  tasksInserted: number;
  pollsInserted: number;
  messagesInserted: number;
  memoriesInserted: number;
  alertsInserted: number;
  reviewsInserted: number;
  aiRequestsInserted: number;
  destinationsInserted: number;
}> {
  if (getMongoStatus() !== 'connected') {
    return {
      usersInserted: 0,
      tripsInserted: 0,
      bookingsInserted: 0,
      budgetsInserted: 0,
      packingInserted: 0,
      tasksInserted: 0,
      pollsInserted: 0,
      messagesInserted: 0,
      memoriesInserted: 0,
      alertsInserted: 0,
      reviewsInserted: 0,
      aiRequestsInserted: 0,
      destinationsInserted: 0,
    };
  }

  let usersInserted = 0;
  let tripsInserted = 0;
  let bookingsInserted = 0;
  let budgetsInserted = 0;
  let packingInserted = 0;
  let tasksInserted = 0;
  let pollsInserted = 0;
  let messagesInserted = 0;
  let memoriesInserted = 0;
  let alertsInserted = 0;
  let reviewsInserted = 0;
  let aiRequestsInserted = 0;
  let destinationsInserted = 0;

  // 1. Seed & Upsert Users (16)
  for (const u of SEED_USERS) {
    await UserModel.findOneAndUpdate({ email: u.email }, { $set: u }, { upsert: true, new: true });
    usersInserted++;
  }

  // 2. Seed & Upsert Trips (16)
  for (const t of SEED_TRIPS) {
    await TripModel.findOneAndUpdate({ id: t.id }, { $set: t }, { upsert: true, new: true });
    tripsInserted++;
  }

  // 3. Seed & Upsert Bookings (18)
  for (const bkg of SEED_BOOKINGS) {
    const existing = await BookingModel.findOne({
      $or: [{ id: bkg.id }, { bookingReference: bkg.bookingReference }],
    });
    if (existing) {
      await BookingModel.updateOne({ _id: existing._id }, { $set: bkg });
    } else {
      await BookingModel.create(bkg);
    }
    bookingsInserted++;
  }

  // 4. Seed & Upsert Budgets (16)
  for (const b of SEED_BUDGETS) {
    await BudgetModel.findOneAndUpdate({ id: b.id }, { $set: b }, { upsert: true, new: true });
    budgetsInserted++;
  }

  // 5. Seed & Upsert Smart Packing Lists (16)
  for (const p of SEED_PACKING) {
    await PackingListModel.findOneAndUpdate({ id: p.id }, { $set: p }, { upsert: true, new: true });
    packingInserted++;
  }

  // 6. Seed & Upsert Tasks (16)
  for (const t of SEED_TASKS) {
    await TaskModel.findOneAndUpdate({ id: t.id }, { $set: t }, { upsert: true, new: true });
    tasksInserted++;
  }

  // 7. Seed & Upsert Polls (16)
  for (const p of SEED_POLLS) {
    await PollModel.findOneAndUpdate({ id: p.id }, { $set: p }, { upsert: true, new: true });
    pollsInserted++;
  }

  // 8. Seed & Upsert Chat Messages (16)
  for (const m of SEED_MESSAGES) {
    await ChatMessageModel.findOneAndUpdate({ id: m.id }, { $set: m }, { upsert: true, new: true });
    messagesInserted++;
  }

  // 9. Seed & Upsert Memories (16)
  for (const m of SEED_MEMORIES) {
    await MemoryModel.findOneAndUpdate({ id: m.id }, { $set: m }, { upsert: true, new: true });
    memoriesInserted++;
  }

  // 10. Seed & Upsert Alerts (16)
  for (const a of SEED_ALERTS) {
    await AlertModel.findOneAndUpdate({ id: a.id }, { $set: a }, { upsert: true, new: true });
    alertsInserted++;
  }

  // 11. Seed & Upsert Reviews (16)
  for (const r of SEED_REVIEWS) {
    await ReviewModel.findOneAndUpdate({ id: r.id }, { $set: r }, { upsert: true, new: true });
    reviewsInserted++;
  }

  // 12. Seed & Insert AI Requests (16)
  const existingAiCount = await AiRequestModel.countDocuments();
  if (existingAiCount < 15) {
    for (const req of SEED_AI_REQUESTS) {
      await AiRequestModel.create(req);
      aiRequestsInserted++;
    }
  } else {
    aiRequestsInserted = existingAiCount;
  }

  // 13. Seed & Upsert Curated Destinations (16)
  for (const d of SEED_DESTINATIONS) {
    await DestinationModel.findOneAndUpdate({ id: d.id }, { $set: d }, { upsert: true, new: true });
    destinationsInserted++;
  }

  console.log(
    `[Data Migration] Seeding completed: ${usersInserted} users, ${tripsInserted} trips, ${bookingsInserted} bookings, ${budgetsInserted} budgets, ${packingInserted} packing lists, ${tasksInserted} tasks, ${pollsInserted} polls, ${messagesInserted} messages, ${memoriesInserted} memories, ${alertsInserted} alerts, ${reviewsInserted} reviews, ${aiRequestsInserted} ai_requests, ${destinationsInserted} destinations.`
  );

  return {
    usersInserted,
    tripsInserted,
    bookingsInserted,
    budgetsInserted,
    packingInserted,
    tasksInserted,
    pollsInserted,
    messagesInserted,
    memoriesInserted,
    alertsInserted,
    reviewsInserted,
    aiRequestsInserted,
    destinationsInserted,
  };
}
